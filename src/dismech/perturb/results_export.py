"""
Run every dismech-perturb scenario and persist the results as a JSON artifact.

``dismech-perturb`` prints its scenario table to a terminal and keeps nothing, so
the numbers a model actually produces never reach the disorder page. This module
runs each ``models/<model_id>.config.yaml`` scenario, evaluates the curated
phenotype thresholds against the result, and writes
``exports/model_runs/<model_id>.json`` — a generated artifact in the same spirit
as ``pathographs/``: committed so the site can render it and reviewers can diff
it, but regenerated by ``just gen-model-results`` rather than hand-edited.

The artifact records, per scenario, the final value of each curated observable,
its fold change against the healthy baseline, and which HP phenotypes the
thresholds activate at what severity. That last part is the point: it is the
step that turns a simulation number into a dismech claim.

**Determinism.** Values are rounded (see ``ROUNDING_DECIMALS``) so that
integrator jitter between machines or tellurium versions does not churn the
committed diff. No timestamps are written for the same reason; provenance is
carried by the sha256 of the config and SBML inputs instead, so a stale artifact
is visible as a hash mismatch rather than a silently wrong table.

Requires tellurium (``uv pip install tellurium``) to *generate*; reading and
rendering the artifact does not.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from dismech.perturb.phenotypes import evaluate_phenotypes
from dismech.perturb.sedml_export import find_disorder_for_model
from dismech.perturb.simulate import (
    ModelConfig,
    load_model_config,
    resolve_scenario_dial,
    run_perturbation,
)
from dismech.yaml_io import safe_load

#: Decimal places kept in the artifact. Six is far finer than any observable's
#: meaningful precision (serum urate in mg/dL, TSH in mIU/L) and far coarser
#: than the ~1e-9 spread seen between integrator paths.
ROUNDING_DECIMALS = 6

DEFAULT_OUTPUT_DIR = Path("exports/model_runs")


def _round(value: float | None) -> float | None:
    if value is None:
        return None
    rounded = round(float(value), ROUNDING_DECIMALS)
    # `round(-4.5e-303, 6)` is -0.0, which json.dumps writes as "-0.0". The sign
    # of a denormal residual is exactly the cross-machine jitter this rounding
    # exists to suppress, and it renders as negative beta-cell mass on the
    # disorder page. Normalise it — note `-0.0 == 0.0`, so a test that only
    # compares values cannot catch this; assert on the sign.
    return 0.0 if rounded == 0 else rounded


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _fold_change(value: float, baseline: float) -> float | None:
    """Fold change against baseline, or None where baseline is zero."""
    if baseline == 0:
        return None
    return value / baseline


@dataclass
class RunResult:
    model_id: str
    payload: dict[str, Any] | None = None
    output_path: Path | None = None
    skipped_reason: str | None = None


def build_observables(config: ModelConfig) -> list[dict[str, Any]]:
    """The curated model variables, in a stable order."""
    observables = []
    for name, mapping in sorted(config.variable_mappings.items()):
        observables.append(
            {
                "name": name,
                "dataset_identifier": mapping.dataset_identifier
                or mapping.sbml_species
                or "",
                "label": mapping.label or name,
            }
        )
    return observables


def threshold_kind(direction: str) -> str:
    """Whether a threshold value is an absolute reading or a baseline ratio.

    ``phenotypes.evaluate_phenotypes`` treats the two directions asymmetrically:
    an ``above`` threshold is compared against the raw value in the observable's
    own unit, while a ``below`` threshold is compared against
    ``value / baseline``. Published side by side with no discriminator, a
    ``below`` threshold of 0.5 beside a "mg/dL" column reads as 0.5 mg/dL when
    it means 50% of baseline — five times the number shown, for urate.
    """
    return "ratio_of_baseline" if direction == "below" else "absolute"


def build_thresholds(config: ModelConfig) -> list[dict[str, Any]]:
    """The curated phenotype activation rules, so the table is self-explaining."""
    return [
        {
            "hp_id": threshold.hp_id,
            "hp_label": threshold.hp_label,
            "model_variable": threshold.model_variable,
            "direction": threshold.direction,
            "threshold_kind": threshold_kind(threshold.direction),
            "threshold": _round(threshold.threshold),
            "severity_scale": [
                [_round(value), name] for value, name in threshold.severity_scale
            ],
        }
        for threshold in config.phenotype_thresholds
    ]


def run_scenarios(
    config: ModelConfig, *, severity_comparable: bool = True
) -> dict[str, Any]:
    """Run the baseline and every scenario, and assemble the artifact body.

    ``severity_comparable=False`` drops the severity tier from each activated
    phenotype while keeping the activation itself: for a bistable model whose
    lesions all land on one attractor, the tier is an artefact of the attractor
    rather than a graded statement about the lesion.
    """
    baseline_dial = config.coupling.baseline_gfr
    baseline = run_perturbation(config, gfr=baseline_dial).variables

    scenarios: list[dict[str, Any]] = []
    for scenario_id, scenario in config.scenarios.items():
        scenario = scenario or {}
        dial = resolve_scenario_dial(config, scenario)
        result = run_perturbation(
            config,
            gfr=dial,
            gene=scenario.get("gene"),
            effect=scenario.get("effect"),
            param_overrides=scenario.get("param_overrides"),
        ).variables

        activated = evaluate_phenotypes(result, baseline, config.phenotype_thresholds)

        scenarios.append(
            {
                "id": scenario_id,
                "label": scenario.get("label", scenario_id),
                "causal_root": scenario.get("causal_root"),
                "gene": scenario.get("gene"),
                "effect": scenario.get("effect"),
                "dial": _round(float(dial)),
                "param_overrides": {
                    key: _round(float(value))
                    for key, value in (scenario.get("param_overrides") or {}).items()
                },
                # Deliberately not "values": Jinja resolves `scenario.values`
                # to the dict method, silently shadowing the key.
                "final_values": {
                    name: _round(value) for name, value in sorted(result.items())
                },
                "fold_change": {
                    name: _round(_fold_change(value, baseline[name]))
                    for name, value in sorted(result.items())
                    if name in baseline
                },
                "phenotypes": [
                    {
                        "hp_id": item.hp_id,
                        "hp_label": item.hp_label,
                        "severity": item.severity if severity_comparable else None,
                        "value_description": item.value_description,
                    }
                    for item in activated
                ],
            }
        )

    return {
        "baseline": {name: _round(value) for name, value in sorted(baseline.items())},
        "baseline_dial": _round(float(baseline_dial)),
        "scenarios": scenarios,
    }


def run_config(
    config_path: Path,
    output_dir: Path = DEFAULT_OUTPUT_DIR,
    *,
    disorders_dir: Path = Path("kb/disorders"),
    write: bool = True,
) -> RunResult:
    """Run every scenario in one config and write its results artifact."""
    with open(config_path) as handle:
        raw = safe_load(handle) or {}
    model_id = str(raw.get("model_id") or config_path.stem)

    disorder = find_disorder_for_model(model_id, disorders_dir)
    config = load_model_config(config_path, disorder=disorder)

    if not config.variable_mappings:
        return RunResult(
            model_id=model_id,
            skipped_reason=(
                "no curated model variables: the disorder entry's "
                "computational_models[].variables has nothing with a "
                "dataset_identifier, so there is nothing to report"
            ),
        )

    sbml_path = config_path.parent / config.sbml_file
    extension_path = (
        config_path.parent / config.extension_file if config.extension_file else None
    )

    # A model whose scenarios are not comparable in severity (see the Topp
    # config) publishes its phenotype activations without a severity tier, plus
    # the caveat explaining why. Both are optional config keys.
    severity_comparable = bool(raw.get("severity_comparable", True))
    caveat = (raw.get("caveat") or "").strip() or None

    payload: dict[str, Any] = {
        "model_id": model_id,
        "disease": (disorder or {}).get("name"),
        "severity_comparable": severity_comparable,
        "caveat": caveat,
        "provenance": {
            "generator": "dismech.perturb.results_export",
            "runner": "dismech-perturb (tellurium / libRoadRunner CVODE)",
            "config_sha256": _sha256(config_path),
            "sbml_file": config.sbml_file,
            "sbml_sha256": _sha256(sbml_path),
            "extension_file": config.extension_file,
            "extension_sha256": (
                _sha256(extension_path)
                if extension_path and extension_path.exists()
                else None
            ),
            "duration_hours": config.coupling.duration_hours,
            "dt_hours": config.coupling.dt_hours,
            "severity_dial": config.coupling.gfr_parameter,
            "rounding_decimals": ROUNDING_DECIMALS,
        },
        "observables": build_observables(config),
        "thresholds": build_thresholds(config),
    }
    payload.update(run_scenarios(config, severity_comparable=severity_comparable))

    output_path = output_dir / f"{model_id}.json"
    if write:
        output_dir.mkdir(parents=True, exist_ok=True)
        output_path.write_text(json.dumps(payload, indent=2, sort_keys=False) + "\n")

    return RunResult(model_id=model_id, payload=payload, output_path=output_path)


def load_results(
    model_id: str, results_dir: Path = DEFAULT_OUTPUT_DIR
) -> dict[str, Any] | None:
    """Read a committed results artifact, or None when the model has no run."""
    path = results_dir / f"{model_id}.json"
    if not path.exists():
        return None
    return json.loads(path.read_text())


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run dismech-perturb scenarios and persist the results"
    )
    parser.add_argument("--models-dir", default="models")
    parser.add_argument("--disorders-dir", default="kb/disorders")
    parser.add_argument("--output", "-o", default=str(DEFAULT_OUTPUT_DIR))
    parser.add_argument("--id", help="Run only this model_id")
    args = parser.parse_args()

    models_dir = Path(args.models_dir)
    paths = sorted(models_dir.glob("*.config.yaml"))
    if args.id:
        paths = [path for path in paths if path.name == f"{args.id}.config.yaml"]
        if not paths:
            parser.error(f"no config found for model_id '{args.id}' in {models_dir}")

    for path in paths:
        result = run_config(
            path, Path(args.output), disorders_dir=Path(args.disorders_dir)
        )
        if result.skipped_reason:
            print(f"SKIP  {result.model_id}: {result.skipped_reason}")
            continue
        scenarios = result.payload["scenarios"]
        activated = sum(1 for item in scenarios if item["phenotypes"])
        print(
            f"OK    {result.model_id}: {len(scenarios)} scenarios "
            f"({activated} activating a phenotype), "
            f"{len(result.payload['observables'])} observables -> {result.output_path}"
        )


if __name__ == "__main__":
    main()
